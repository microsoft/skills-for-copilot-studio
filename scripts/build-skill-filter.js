#!/usr/bin/env node
/**
 * Generates hooks/filter-skills.js from SKILL.md frontmatter.
 *
 * Reads agent-types from every skills/SKILL.md and builds the
 * blocked skill lists into the hook. Run after adding/changing skills:
 *
 *   node scripts/build-skill-filter.js
 *
 * CI validates the committed hook matches what this script generates.
 */

const fs = require('fs');
const path = require('path');

const skillsDir = path.join(__dirname, '..', 'skills');
const outputFile = path.join(__dirname, '..', 'hooks', 'filter-skills.js');

const classic = [];
const modern = [];

for (const entry of fs.readdirSync(skillsDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  if (entry.name.startsWith('int-')) continue;

  const skillFile = path.join(skillsDir, entry.name, 'SKILL.md');
  if (!fs.existsSync(skillFile)) continue;

  const content = fs.readFileSync(skillFile, 'utf8');
  const match = content.match(/^agent-types:\s*(.+)$/m);
  if (!match) continue;

  const agentType = match[1].trim();
  if (agentType === 'classic') classic.push(entry.name);
  else if (agentType === 'modern') modern.push(entry.name);
}

classic.sort();
modern.sort();

const lines = [
  '// AUTO-GENERATED by scripts/build-skill-filter.js \u2014 do not edit manually',
  '// Run: node scripts/build-skill-filter.js',
  "const fs = require('fs');",
  "const path = require('path');",
  '',
  'const CLASSIC_ONLY = new Set(' + JSON.stringify(classic) + ');',
  'const MODERN_ONLY = new Set(' + JSON.stringify(modern) + ');',
  '',
  'function detectAgentType(cwd) {',
  '  function findSettings(dir, depth) {',
  '    if (depth > 4) return null;',
  '    try {',
  '      const entries = fs.readdirSync(dir, { withFileTypes: true });',
  '      for (const e of entries) {',
  "        if (e.name === 'settings.mcs.yml' && e.isFile()) return path.join(dir, e.name);",
  '      }',
  '      for (const e of entries) {',
  "        if (e.isDirectory() && !e.name.startsWith('.') && e.name !== 'node_modules') {",
  '          const found = findSettings(path.join(dir, e.name), depth + 1);',
  '          if (found) return found;',
  '        }',
  '      }',
  '    } catch {}',
  '    return null;',
  '  }',
  '',
  '  const settingsPath = findSettings(cwd, 0);',
  "  if (!settingsPath) return '';",
  '',
  "  const content = fs.readFileSync(settingsPath, 'utf8');",
  '  if (/template:\\s*cliagent-/.test(content) ||',
  '      /\\$kind:\\s*CLICopilotRecognizer/.test(content) ||',
  '      /kind:\\s*CLICopilotRecognizer/.test(content) ||',
  '      /kind:\\s*CLIAgentRecognizer/.test(content)) {',
  "    return 'modern';",
  '  }',
  "  return 'classic';",
  '}',
  '',
  "let input = '';",
  "process.stdin.setEncoding('utf8');",
  "process.stdin.on('data', (chunk) => { input += chunk; });",
  "process.stdin.on('end', () => {",
  '  try {',
  '    const data = JSON.parse(input);',
  "    const skillField = (data.tool_input && data.tool_input.skill) || '';",
  "    const command = skillField.includes(':') ? skillField.split(':').pop() : skillField;",
  '    if (!command) process.exit(0);',
  '',
  '    const cwd = data.cwd || process.cwd();',
  '    const agentType = detectAgentType(cwd);',
  '    if (!agentType) process.exit(0);',
  '',
  '    const blocked = agentType === \'modern\' ? CLASSIC_ONLY : MODERN_ONLY;',
  '    if (blocked.has(command)) {',
  "      const opposite = agentType === 'modern' ? 'classic' : 'modern';",
  '      process.stdout.write(JSON.stringify({',
  "        decision: 'block',",
  "        reason: 'The \"' + command + '\" skill is for ' + opposite + ' agents only. This workspace contains a ' + agentType + ' agent.'",
  '      }));',
  '    }',
  '  } catch {}',
  '});',
  '',
];

fs.writeFileSync(outputFile, lines.join('\n'));
console.log('Generated ' + path.relative(process.cwd(), outputFile));
console.log('  Classic-only: ' + classic.join(', '));
console.log('  Modern-only:  ' + modern.join(', '));
